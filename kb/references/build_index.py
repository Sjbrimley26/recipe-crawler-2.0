#!/usr/bin/env python3
"""Regenerate every index.md in an OKF bundle from the concepts' own frontmatter.

The concept files are the source of truth (hand- or agent-edited, and they keep any human
`verified` entries). Only index.md files are generated, so re-running never destroys a sign-off.

    python3 references/build_index.py [BUNDLE_ROOT]      # default: the bundle containing this script

Conventions it reads:
  <root>/_bundle.txt   first line = bundle title, rest = intro paragraph
  <dir>/_about.txt     one-line (or longer) blurb for a subdirectory; first line is the index blurb
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent)
TITLE_FILE = "_bundle.txt"


def front(p: pathlib.Path) -> dict:
    """Read the quoted scalars we emit. Deliberately tolerant: a concept with only `type` is valid."""
    m = re.match(r"^---\n(.*?)\n---\n", p.read_text(encoding="utf-8"), re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            k = re.match(r'^(\w+):\s*"(.*)"\s*$', line)
            if k:
                out[k.group(1)] = k.group(2).replace('\\"', '"')
    return out


def build(d: pathlib.Path):
    rel = "/" + str(d.relative_to(ROOT)).strip(".") if d != ROOT else ""
    concepts = sorted(p for p in d.glob("*.md") if p.name not in ("index.md", "log.md"))
    subdirs = sorted(p for p in d.iterdir() if p.is_dir() and any(p.rglob("*.md")))
    lines = []
    if d == ROOT:
        meta = (d / TITLE_FILE).read_text(encoding="utf-8").strip().split("\n", 1)
        lines += ['---', 'okf_version: "0.2"', '---', '', f"# {meta[0]}", ""]
        if len(meta) > 1:
            lines += [meta[1].strip(), ""]
        lines += ["Generated by `references/build_index.py`; edit the concepts, not this page.", ""]
    else:
        lines += [f"# {d.name}", ""]
        about = d / "_about.txt"
        if about.exists():
            lines += [about.read_text(encoding="utf-8").strip(), ""]
    for s in subdirs:
        about = s / "_about.txt"
        blurb = about.read_text(encoding="utf-8").strip().splitlines()[0] if about.exists() else ""
        lines.append(f"* [{s.name}/]({rel}/{s.name}/index.md)" + (f" - {blurb}" if blurb else ""))
    if subdirs:
        lines.append("")
    for c in concepts:
        f = front(c)
        lines.append(f"* [{f.get('title', c.stem)}]({rel}/{c.name})" +
                     (f" - {f['description']}" if f.get("description") else ""))
    if (d / "log.md").exists():
        lines += ["", f"* [log.md]({rel}/log.md) - change history, newest first."]
    (d / "index.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    for s in subdirs:
        build(s)


build(ROOT)
print(f"indexes rebuilt under {ROOT}")
